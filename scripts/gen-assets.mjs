/* Generate src/lib/assets-data.js from the image files in public/assets/.
 *
 * Why: the repo sync path to GitHub only supports UTF-8 text files, so the
 * product images and logo are embedded in the codebase as data URIs instead
 * of being served as binary files.
 *
 * Usage:
 *   1. Put/replace image files in public/assets/ (that folder is gitignored;
 *      it only serves as the local source for this script).
 *   2. Run:  node scripts/gen-assets.mjs
 *   3. Commit the regenerated src/lib/assets-data.js.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = join(root, "public", "assets");
const outFile = join(root, "src", "lib", "assets-data.js");

const MIME = {
  ".webp": "image/webp",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
};

function identFor(filename) {
  return filename
    .replace(/\.[^.]+$/, "")
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_");
}

if (!existsSync(assetsDir)) {
  console.error(
    `Folder ${assetsDir} tidak ditemukan. Buat folder itu dan isi dengan file gambar sumber dulu.`
  );
  process.exit(1);
}

const files = readdirSync(assetsDir)
  .filter((f) => MIME[extname(f).toLowerCase()])
  .sort();

if (files.length === 0) {
  console.error(`No image files found in ${assetsDir}`);
  process.exit(1);
}

const lines = [
  "/* GENERATED by scripts/gen-assets.mjs — do not edit by hand.",
  "   Images are embedded as data URIs because the repo sync path only",
  "   supports UTF-8 text files. To change an image: replace the source",
  "   file in the public assets folder and re-run the generator script. */",
  "",
];

const entries = [];
for (const f of files) {
  const mime = MIME[extname(f).toLowerCase()];
  const b64 = readFileSync(join(assetsDir, f)).toString("base64");
  const ident = identFor(f);
  lines.push(`export const ${ident} = "data:${mime};base64,${b64}";`, "");
  entries.push(`  ${JSON.stringify(f)}: ${ident},`);
}

lines.push("export const ASSETS = {", ...entries, "};", "");
const logo = files.find((f) => f.startsWith("logo-"));
if (logo) lines.push(`export const LOGO = ${identFor(logo)};`, "");

writeFileSync(outFile, lines.join("\n"));
console.log(`Wrote ${outFile} with ${files.length} assets: ${files.join(", ")}`);
